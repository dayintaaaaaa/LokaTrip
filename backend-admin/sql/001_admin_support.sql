create table if not exists public.admin_notifikasi (
  id_notifikasi_admin bigint generated by default as identity primary key,
  id_admin integer not null references public.admin_lokatrip(id_admin) on delete cascade,
  judul varchar not null,
  isi text not null,
  kategori varchar not null default 'sistem'
    check (kategori in ('dokumen', 'perizinan', 'mitra', 'sistem')),
  referensi_tabel varchar,
  referensi_id varchar,
  status_baca boolean not null default false,
  dibuat_pada timestamptz not null default now()
);

create index if not exists admin_notifikasi_admin_unread_idx
  on public.admin_notifikasi (id_admin, status_baca, dibuat_pada desc);

create table if not exists public.preferensi_admin (
  id_admin integer primary key references public.admin_lokatrip(id_admin) on delete cascade,
  bahasa varchar not null default 'id',
  zona_waktu varchar not null default 'Asia/Jakarta',
  preferensi jsonb not null default '{"push_notification": true, "eskalasi_perizinan": true, "ringkasan_aktivitas": true}'::jsonb
    check (jsonb_typeof(preferensi) = 'object'),
  diperbarui_pada timestamptz not null default now()
);

create table if not exists public.riwayat_aktivitas_admin (
  id_aktivitas_admin bigint generated by default as identity primary key,
  id_admin integer references public.admin_lokatrip(id_admin) on delete set null,
  aksi varchar not null,
  target_tabel varchar not null,
  target_id varchar,
  detail jsonb not null default '{}'::jsonb check (jsonb_typeof(detail) = 'object'),
  dibuat_pada timestamptz not null default now()
);

create index if not exists riwayat_aktivitas_admin_created_idx
  on public.riwayat_aktivitas_admin (dibuat_pada desc);
create index if not exists riwayat_aktivitas_admin_actor_idx
  on public.riwayat_aktivitas_admin (id_admin, dibuat_pada desc);

-- Sparse overrides preserve existing partner states until an admin changes them.
create table if not exists public.status_mitra_admin (
  id_mitra integer primary key references public.admin_wisata(id_mitra) on delete cascade,
  status_mitra varchar not null
    check (status_mitra in ('menunggu_verifikasi', 'aktif', 'ditolak', 'ditangguhkan')),
  ditampilkan_di_beranda boolean not null default false,
  catatan_admin text,
  diperbarui_oleh integer references public.admin_lokatrip(id_admin) on delete set null,
  diperbarui_pada timestamptz not null default now()
);

